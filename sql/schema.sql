-- Tabelas da parte 2. Cada uma tem chave primária.
-- S1 é a umidade, S2 é o pH e S3 é o par fósforo/potássio.

CREATE TABLE ft_culturas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(80) NOT NULL,
    nome_cientifico VARCHAR2(120) NOT NULL,
    fase VARCHAR2(40) NOT NULL,
    ph_min NUMBER(4,2) NOT NULL,
    ph_max NUMBER(4,2) NOT NULL,
    umidade_ligar NUMBER(5,2) NOT NULL,
    umidade_desligar NUMBER(5,2) NOT NULL,
    observacao VARCHAR2(400) NOT NULL,
    CONSTRAINT uq_ft_culturas_nome UNIQUE (nome)
);

CREATE TABLE ft_manejo (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cultura_id NUMBER NOT NULL,
    vazao_l_h NUMBER(8,2) NOT NULL,
    area_m2 NUMBER(8,2) NOT NULL,
    descricao VARCHAR2(400) NOT NULL,
    CONSTRAINT uq_ft_manejo_cultura UNIQUE (cultura_id),
    CONSTRAINT fk_ft_manejo_cultura FOREIGN KEY (cultura_id) REFERENCES ft_culturas (id)
);

CREATE TABLE ft_insumos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cultura_id NUMBER NOT NULL,
    nome VARCHAR2(40) NOT NULL,
    dose_min_kg_ha NUMBER(8,2) NOT NULL,
    dose_max_kg_ha NUMBER(8,2) NOT NULL,
    CONSTRAINT uq_ft_insumo UNIQUE (cultura_id, nome),
    CONSTRAINT fk_ft_insumos_cultura FOREIGN KEY (cultura_id) REFERENCES ft_culturas (id)
);

CREATE TABLE ft_leituras (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cultura_id NUMBER NOT NULL,
    data_hora TIMESTAMP NOT NULL,
    umidade NUMBER(6,2) NOT NULL,
    ph NUMBER(5,2) NOT NULL,
    fosforo NUMBER(1) NOT NULL,
    potassio NUMBER(1) NOT NULL,
    nitrogenio NUMBER(1) NOT NULL,
    chuva NUMBER(1) NOT NULL,
    bomba NUMBER(1) NOT NULL,
    origem VARCHAR2(20) NOT NULL,
    umidade_suavizada NUMBER(6,2) NOT NULL,
    ph_suavizado NUMBER(5,2) NOT NULL,
    CONSTRAINT uq_ft_leituras_data UNIQUE (data_hora),
    CONSTRAINT fk_ft_leituras_cultura FOREIGN KEY (cultura_id) REFERENCES ft_culturas (id),
    CONSTRAINT ck_ft_umidade CHECK (umidade BETWEEN 0 AND 100),
    CONSTRAINT ck_ft_ph CHECK (ph BETWEEN 0 AND 14),
    CONSTRAINT ck_ft_fosforo CHECK (fosforo IN (0, 1)),
    CONSTRAINT ck_ft_potassio CHECK (potassio IN (0, 1)),
    CONSTRAINT ck_ft_nitrogenio CHECK (nitrogenio IN (0, 1)),
    CONSTRAINT ck_ft_chuva CHECK (chuva IN (0, 1)),
    CONSTRAINT ck_ft_bomba CHECK (bomba IN (0, 1)),
    CONSTRAINT ck_ft_origem CHECK (origem IN ('simulada', 'serial'))
);

CREATE TABLE ft_historico_bomba (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cultura_id NUMBER NOT NULL,
    inicio TIMESTAMP NOT NULL,
    fim TIMESTAMP NOT NULL,
    horas NUMBER(8,2) NOT NULL,
    vazao_l_h NUMBER(8,2) NOT NULL,
    volume_litros NUMBER(12,2) NOT NULL,
    CONSTRAINT uq_ft_bomba_inicio UNIQUE (inicio),
    CONSTRAINT fk_ft_bomba_cultura FOREIGN KEY (cultura_id) REFERENCES ft_culturas (id)
);
